def test_02_cell_censoring_filter_then_parent_median_dedup(code_cells):
    tree = ast.parse(_cell_with(code_cells, STEP2))

    # censoring filter: an equality compare keeping standard_relation == "="
    eq_nodes = [
        n
        for n in ast.walk(tree)
        if isinstance(n, ast.Compare)
        and any(isinstance(op, ast.Eq) for op in n.ops)
        and any(_mentions(o, "standard_relation") for o in (n.left, *n.comparators))
        and any(_mentions(o, "=") for o in (n.left, *n.comparators))
    ]
    assert eq_nodes, "02 cell must keep only standard_relation == '=' (censoring filter)"

    parent_grp = _groupby_calls(tree, "parent_smiles")
    assert parent_grp, "02 cell must deduplicate with groupby('parent_smiles')"
    assert not _groupby_calls(tree, "canonical_smiles"), (
        "02 cell must not group by canonical_smiles (salt variants of one parent)"
    )
    assert min(n.lineno for n in eq_nodes) < min(n.lineno for n in parent_grp), (
        "the censoring filter must run before the parent_smiles groupby"
    )

    # median pIC50 per parent, via agg(..., "median") or .median()
    median = any(
        (isinstance(n, ast.Constant) and n.value == "median")
        or (isinstance(n, ast.Attribute) and n.attr == "median")
        for n in ast.walk(tree)
    )
    assert median, "02 cell must collapse each parent group to the median pIC50"


def test_03_cell_featurizes_parent_smiles(code_cells):
    tree = ast.parse(_cell_with(code_cells, STEP3))
    consts = {n.value for n in ast.walk(tree) if isinstance(n, ast.Constant)}
    assert "parent_smiles" in consts, "03 cell must select the parent_smiles column"

    # a direct df["canonical_smiles"] read would re-fingerprint salt variants
    # and desynchronize the smiles array from the 02 dedup unit (M1)
    hardcoded = [
        n
        for n in ast.walk(tree)
        if isinstance(n, ast.Subscript)
        and isinstance(n.slice, ast.Constant)
        and n.slice.value == "canonical_smiles"
    ]
    assert not hardcoded, "03 cell must not featurize df['canonical_smiles'] directly"


def test_04_cell_uses_shuffled_fixed_seed_cv(code_cells):
    tree = ast.parse(_cell_with(code_cells, STEP4))
    kfold_calls = [
        n
        for n in ast.walk(tree)
        if isinstance(n, ast.Call)
        and (
            (isinstance(n.func, ast.Name) and n.func.id == "KFold")
            or (isinstance(n.func, ast.Attribute) and n.func.attr == "KFold")
        )
    ]
    assert kfold_calls, "04 cell must build a KFold splitter for GridSearchCV"
    for call in kfold_calls:
        shuffle = [kw for kw in call.keywords if kw.arg == "shuffle"]
        assert shuffle, "KFold must pass shuffle= explicitly (unshuffled CV leaked chemotype blocks)"
        val = shuffle[0].value
        assert isinstance(val, ast.Constant) and val.value is True, "CV folds must have shuffle=True"
        assert any(kw.arg == "random_state" for kw in call.keywords), (
            "shuffled CV must pin random_state for reproducibility"
        )

    # CV_FOLDS, when assigned in the cell, stays at 5
    for n in ast.walk(tree):
        if isinstance(n, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "CV_FOLDS" for t in n.targets
        ):
            assert isinstance(n.value, ast.Constant) and n.value.value == 5, (
                "CV_FOLDS must remain 5-fold"
            )
